import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = resolve(root, 'docs/style-handoff/infinidata.css');
const read = (path) => readFile(resolve(root, path), 'utf8');

// Keep the exported styles tied to the website's original sources.
const source = await read('src/app.css');
const imports = [...source.matchAll(/^@import ['"]([^'"]+)['"];\s*$/gm)];
const base = source.replace(/^@import ['"][^'"]+['"];\s*$/gm, '').trim();
const sections = [
	`/*!
 * Infinidata Lab — standalone website styles
 * Generated by: npm run export:styles
 * Link from plain HTML: <link rel="stylesheet" href="infinidata.css">
 * Includes the original variable fonts as data URLs; no build tools or CDN needed.
 * Font copyright notices and SIL Open Font Licenses are included below.
 * Default theme follows the OS. Override with data-theme="light" or "dark" on <html>.
 */`,
	`/* Source: src/app.css (font imports embedded below) */\n${base}`
];

for (const name of ['Brand', 'Nav', 'Footer', 'Prose']) {
	const path = `src/lib/components/${name}.svelte`;
	const component = await read(path);
	const match = component.match(/<style>\s*\n([\s\S]*?)<\/style>/);
	if (!match) throw new Error(`No style block found in ${path}`);
	let css = match[1].replace(/^\t/gm, '').trim();
	css = css.replace(/:global\(([^)]+)\)/g, '$1');
	// Svelte normally scopes these short selectors to their component.
	if (name === 'Brand') css = css.replaceAll('.word', '.brand .word');
	if (name === 'Nav') {
		css = css.replaceAll('.burger', '.nav .burger').replaceAll('.join', '.nav .join');
	}
	if (name === 'Footer') {
		css = css
			.replace(/^h5(?=\s*\{)/gm, '.footer h5')
			.replaceAll('.footer-grid a', '.footer-grid a:not(.brand)')
			.replaceAll('.blurb', '.footer .blurb')
			.replaceAll('.socials', '.footer .socials');
	}
	sections.push(`/* Source: ${path} (portable component styles) */\n${css}`);
}

// Embed all subsets referenced by the site's imports, preserving character coverage,
// variable weight ranges, unicode ranges, and the original redistribution licenses.
let fontCount = 0;
for (const [, packageName] of imports) {
	if (!packageName.startsWith('@fontsource-variable/')) {
		throw new Error(`Unsupported CSS import: ${packageName}`);
	}
	const packageDir = resolve(root, 'node_modules', packageName);
	const license = await readFile(resolve(packageDir, 'LICENSE'), 'utf8');
	let css = await readFile(resolve(packageDir, 'index.css'), 'utf8');
	const urls = [...css.matchAll(/url\((\.\/files\/[^)]+)\)/g)];
	if (!urls.length) throw new Error(`No fonts found in ${packageName}`);
	for (const [url, path] of urls) {
		const font = await readFile(resolve(packageDir, path));
		css = css.replace(url, `url("data:font/woff2;base64,${font.toString('base64')}")`);
		fontCount++;
	}
	sections.push(`/*! ${packageName} — original font license\n${license.trim()}\n*/\n\n${css.trim()}`);
}

await mkdir(dirname(output), { recursive: true });
await writeFile(output, sections.join('\n\n') + '\n');
console.log(`Exported docs/style-handoff/infinidata.css with ${fontCount} embedded font subsets.`);
